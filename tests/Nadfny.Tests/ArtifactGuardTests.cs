using System.Diagnostics;
using Nadfny.Core;
using Nadfny.Features.Artifacts;

namespace Nadfny.Tests;

/// <summary>
/// The promise under test: deleting build output never deletes source code.
/// Uses real git repos in a throwaway folder.
/// </summary>
public sealed class ArtifactGuardTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "nadfny-guard-" + Guid.NewGuid().ToString("N"));

    public ArtifactGuardTests() => Directory.CreateDirectory(_root);

    public void Dispose()
    {
        if (Directory.Exists(_root)) SafeDeleter.DeletePermanently(_root);
    }

    private string P(params string[] parts) => Path.Combine([_root, .. parts]);

    private string Write(string relative, string content = "x")
    {
        var path = P(relative);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
        return path;
    }

    private void Git(string repo, params string[] args)
    {
        var psi = new ProcessStartInfo("git") { WorkingDirectory = P(repo), UseShellExecute = false, CreateNoWindow = true, RedirectStandardOutput = true, RedirectStandardError = true };
        foreach (var a in (string[])["-c", "user.name=t", "-c", "user.email=t@example.invalid", "-c", "core.autocrlf=false", .. args]) psi.ArgumentList.Add(a);
        using var p = Process.Start(psi)!;
        p.WaitForExit();
        Assert.True(p.ExitCode == 0, $"git {string.Join(' ', args)}: {p.StandardError.ReadToEnd()}");
    }

    /// <summary>A .NET project in git with the standard bin/obj ignore rules and its source committed.</summary>
    private void DotNetRepo(string name)
    {
        Write($@"{name}\.gitignore", "bin/\nobj/\nnode_modules/\n");
        Write($@"{name}\Api\Api.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        Write($@"{name}\Api\Program.cs", "Console.WriteLine();");
        Write($@"{name}\Api\Controllers\HomeController.cs", "class HomeController {}");
        Directory.CreateDirectory(P(name));
        Git(name, "init", "-q");
        Git(name, "add", ".");
        Git(name, "commit", "-qm", "init");
    }

    private static async Task<GuardVerdict> Verdict(string folder) =>
        Assert.Single(await ArtifactGuard.EvaluateAsync([folder], CancellationToken.None));

    [Fact]
    public async Task IgnoredBinWithOnlyBuildOutput_IsDeletable()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\bin\Debug\net10.0\Api.dll");
        Write(@"repo\Api\bin\Debug\net10.0\Api.pdb");
        Write(@"repo\Api\bin\Debug\net10.0\appsettings.json");

        var v = await Verdict(P("repo", "Api", "bin"));

        Assert.True(v.Deletable, v.Reason);
    }

    [Fact]
    public async Task ObjWithCompilerGeneratedCsFiles_IsDeletable()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\obj\Debug\net10.0\Api.AssemblyInfo.cs");
        Write(@"repo\Api\obj\Debug\net10.0\Api.GlobalUsings.g.cs");
        Write(@"repo\Api\obj\Debug\net10.0\Api.AssemblyAttributes.cs");
        Write(@"repo\Api\obj\Debug\net10.0\Pages\Index.razor.g.cs");
        Write(@"repo\Api\obj\Api.csproj.nuget.g.props");
        Write(@"repo\Api\obj\project.assets.json");

        var v = await Verdict(P("repo", "Api", "obj"));

        Assert.True(v.Deletable, v.Reason);
    }

    [Fact]
    public async Task ObjWithGeneratorMarkedFiles_IsDeletable()
    {
        DotNetRepo("repo");
        // Real headers seen in obj/: Roslyn/MSBuild generators and Android stubs.
        Write(@"repo\Api\obj\Debug\net10.0\EmbeddedAttribute.cs", "// <auto-generated/>\nnamespace Microsoft.CodeAnalysis { }");
        Write(@"repo\Api\obj\Debug\net10.0\Api.MvcApplicationPartsAssemblyInfo.cs", "//------\n// <auto-generated>\n//     This code was generated by a tool.\n");
        Write(@"repo\Api\obj\Debug\net10.0\ar\Api.resources.cs", "// <auto-generated>\n");
        Write(@"repo\Api\obj\Debug\net10.0-android\android\src\R.java", "/* AUTO-GENERATED FILE.  DO NOT MODIFY. */");
        Write(@"repo\Api\obj\Debug\net10.0-android\android\src\ContainerView.java", "package crc64; public class ContainerView {}");
        Write(@"repo\Api\obj\Api.csproj.EntityFrameworkCore.targets", "<Project />");
        Write(@"repo\Api\obj\Debug\net10.0\staticwebassets\msbuild.build.Api.props", "<Project />");

        var v = await Verdict(P("repo", "Api", "obj"));

        Assert.True(v.Deletable, v.Reason);
    }

    [Fact]
    public async Task ObjWithAnUnmarkedCsFile_IsKept()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\obj\Debug\net10.0\Api.AssemblyInfo.cs", "// <auto-generated/>");
        Write(@"repo\Api\obj\Backup\MyService.cs", "public class MyService { /* real work */ }");

        var v = await Verdict(P("repo", "Api", "obj"));

        Assert.False(v.Deletable);
        Assert.Contains("MyService.cs", v.Reason);
    }

    [Fact]
    public async Task BinWithACommittedCsFile_IsKept()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\bin\Tools\Generator.cs", "class Generator {}");
        Git("repo", "add", "-f", "Api/bin/Tools/Generator.cs");
        Git("repo", "commit", "-qm", "tool in bin");

        var v = await Verdict(P("repo", "Api", "bin"));

        Assert.False(v.Deletable);
        Assert.Contains("tracked by git", v.Reason);
    }

    [Fact]
    public async Task IgnoredBinWithAHandWrittenCsFile_IsStillKept()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\bin\Debug\Api.dll");
        Write(@"repo\Api\bin\Scratch\Notes.cs", "// my work, never committed");

        var v = await Verdict(P("repo", "Api", "bin"));

        Assert.False(v.Deletable);
        Assert.Contains("Notes.cs", v.Reason);
    }

    [Theory]
    [InlineData("Helper.cs")]
    [InlineData("Model.vb")]
    [InlineData("Old.csproj")]
    [InlineData("Page.razor")]
    [InlineData("View.cshtml")]
    [InlineData("App.sln")]
    [InlineData("script.py")]
    public async Task OutsideGit_AnySourceFileKeepsTheFolder(string file)
    {
        Write(@"loose\Api\Api.csproj");
        Write(@"loose\Api\bin\Debug\Api.dll");
        Write($@"loose\Api\bin\{file}");

        var v = await Verdict(P("loose", "Api", "bin"));

        Assert.False(v.Deletable, $"{file} should keep the folder");
    }

    [Fact]
    public async Task NodeModulesWithTypeScriptDeclarations_IsDeletable()
    {
        Write(@"web\package.json", "{}");
        Write(@"web\node_modules\lib\index.ts");
        Write(@"web\node_modules\lib\index.d.ts");

        var v = await Verdict(P("web", "node_modules"));

        Assert.True(v.Deletable, v.Reason);
    }

    [Fact]
    public async Task EndToEnd_DeletesBinAndObjButEveryCsFileSurvives()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\bin\Debug\Api.dll");
        Write(@"repo\Api\obj\Debug\Api.AssemblyInfo.cs");
        var sourceBefore = Directory.GetFiles(P("repo"), "*.cs", SearchOption.AllDirectories)
            .Where(f => !f.Contains(@"\obj\")).Order().ToList();
        var service = new ArtifactService();
        var found = await service.ScanAsync([_root], _ => { }, ScanProgress.None, CancellationToken.None);

        var (removed, _, failed) = await service.RemoveAsync([.. found.Select(a => a.Path)], OpReporter.None, CancellationToken.None);

        Assert.Equal(2, removed);
        Assert.Empty(failed);
        Assert.False(Directory.Exists(P("repo", "Api", "bin")));
        Assert.False(Directory.Exists(P("repo", "Api", "obj")));
        var sourceAfter = Directory.GetFiles(P("repo"), "*.cs", SearchOption.AllDirectories).Order().ToList();
        Assert.Equal(sourceBefore, sourceAfter);
        Assert.True(File.Exists(P("repo", "Api", "Api.csproj")));
    }

    [Fact]
    public async Task EndToEnd_SourceAddedAfterTheScanIsStillProtected()
    {
        DotNetRepo("repo");
        Write(@"repo\Api\bin\Debug\Api.dll");
        var service = new ArtifactService();
        var found = await service.ScanAsync([_root], _ => { }, ScanProgress.None, CancellationToken.None);
        Write(@"repo\Api\bin\Debug\JustWrote.cs", "class JustWrote {}"); // appears between scan and delete

        var (removed, _, failed) = await service.RemoveAsync([.. found.Select(a => a.Path)], OpReporter.None, CancellationToken.None);

        Assert.Equal(0, removed);
        Assert.Contains(failed, f => f.Contains("JustWrote.cs"));
        Assert.True(File.Exists(P("repo", "Api", "bin", "Debug", "JustWrote.cs")));
        Assert.True(File.Exists(P("repo", "Api", "bin", "Debug", "Api.dll")));
    }
}
