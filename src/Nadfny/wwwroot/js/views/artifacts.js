import { removeArtifacts, reveal, scanArtifacts } from '../actions.js';
import { button, emptyState, h, icon, sizeCell, skeletonList } from '../dom.js';
import { ago, bytes, daysSince, plural } from '../format.js';
import { state, update } from '../store.js';
import { checkbox, rowWrap, segmented } from './common.js';
import { growthSize } from './history.js';

const KINDS = [
  ['all', 'All', () => true],
  ['node', 'node_modules', (a) => a.kind === 'node_modules'],
  ['dotnet', 'bin & obj', (a) => a.kind === 'bin' || a.kind === 'obj'],
  ['other', 'Other', (a) => !['node_modules', 'bin', 'obj'].includes(a.kind)],
];
const AGES = [[0, 'Any age'], [30, 'Untouched 30+ days'], [90, '90+ days'], [180, '6+ months'], [365, '1+ year']];

export function visibleArtifacts() {
  const kind = KINDS.find(([k]) => k === state.artifacts.kind)?.[2] ?? (() => true);
  const age = state.artifacts.age;
  return [...state.artifacts.items.values()].filter((a) => kind(a)
    && (age === 0 || (a.projectLastUsedUtc && daysSince(a.projectLastUsedUtc) >= age)));
}

export function groupArtifacts(items, sort = 'size') {
  const groups = new Map();
  for (const a of items) {
    const key = a.projectPath;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(a);
  }
  return [...groups.entries()]
    .map(([key, list]) => ({ key, list, total: list.reduce((s, a) => s + a.bytes, 0),
      lastUsed: list.map(a => a.projectLastUsedUtc).filter(Boolean).sort().pop() }))
    .sort((a, b) => {
      if (sort === 'oldest') {
        if (!a.lastUsed && b.lastUsed) return 1;
        if (a.lastUsed && !b.lastUsed) return -1;
        const age = new Date(a.lastUsed).getTime() - new Date(b.lastUsed).getTime();
        if (age) return age;
      }
      return b.total - a.total;
    });
}

export const artifactsView = {
  id: 'artifacts',
  title: 'Build output',
  icon: 'hammer',

  subtitle() {
    const items = [...state.artifacts.items.values()];
    const total = items.reduce((a, x) => a + x.bytes, 0);
    if (state.artifacts.status === 'scanning') return `Looking for node_modules, bin, obj and friends… ${bytes(total)} so far`;
    if (!items.length) return 'Folders your tools regenerate on the next install or build';
    return `${plural(items.length, 'folder')} using ${bytes(total)}. All of it is regenerated by the next install or build.`;
  },

  actions() {
    return [button('Rescan', { icon: 'arrow-clockwise', onClick: scanArtifacts, disabled: state.artifacts.status === 'scanning', key: 'rescan' })];
  },

  render() {
    const st = state.artifacts;
    if (st.status === 'error') return emptyState({ ic: 'warning-circle', error: true, title: 'Scan failed', text: st.error, action: button('Try again', { onClick: scanArtifacts }) });
    if (st.items.size === 0 && st.status === 'scanning') return skeletonList(6);
    if (st.items.size === 0) return emptyState({ ic: 'hammer', title: 'No build output found', text: 'Nothing regenerable in your scan locations. Add a location from the sidebar if your projects live elsewhere.' });

    const items = visibleArtifacts();
    const ordered = groupArtifacts(items, st.sort);
    const max = Math.max(1, ...ordered.map((g) => g.total));
    const allSelected = items.length > 0 && items.every((a) => state.selection.artifacts.has(a.path));

    return h('div', null,
      h('div', { class: 'filters' },
        segmented(KINDS.map(([value, label]) => ({ value, label })), st.kind, (v) => update((s) => { s.artifacts.kind = v; }), 'Folder kind'),
        segmented(AGES.map(([value, label]) => ({ value, label })), st.age, (v) => update((s) => { s.artifacts.age = v; }), 'Last used'),
        segmented([{ value: 'size', label: 'Size' }, { value: 'oldest', label: 'Oldest first' }], st.sort ?? 'size',
          (v) => update((s) => { s.artifacts.sort = v; }), 'Sort projects'),
        h('span', { class: 'spacer' }),
        items.length > 0 && button(allSelected ? 'Deselect all' : `Select all ${items.length}`, {
          variant: 'quiet', small: true, key: 'select-all',
          onClick: () => update((s) => items.forEach((a) => (allSelected ? s.selection.artifacts.delete(a.path) : s.selection.artifacts.add(a.path)))),
        })),
      items.length === 0
        ? emptyState({ ic: 'check-circle', title: 'Nothing matches', text: 'Try another kind or age.' })
        : h('div', { class: 'list' }, ordered.map((g) => projectRow(g, max))));
  },
};

function projectRow({ key, list, total, lastUsed }, max) {
  const sel = state.selection.artifacts;
  const selected = list.filter((a) => sel.has(a.path)).length;
  const expanded = state.artifacts.expanded.has(key);
  const kinds = summarizeKinds(list);
  const isWorktree = state.worktrees.items.has(key);
  const setAll = (on) => update((s) => list.forEach((a) => (on ? s.selection.artifacts.add(a.path) : s.selection.artifacts.delete(a.path))));
  const toggleOpen = () => update((s) => (expanded ? s.artifacts.expanded.delete(key) : s.artifacts.expanded.add(key)));

  return [
    rowWrap(key, h('div', { class: `row clickable ${selected === list.length ? 'is-selected' : ''}`, onclick: toggleOpen },
      checkbox({ checked: selected === list.length, indeterminate: selected > 0 && selected < list.length, label: `Select build output in ${key.split('\\').pop()}`, key: `art-${key}`, onChange: setAll }),
      h('div', { style: { minWidth: 0 } },
        h('div', { class: 'row-title' },
          h('button', { class: 'icon-btn', type: 'button', 'aria-expanded': String(expanded), 'aria-label': expanded ? 'Collapse' : 'Expand', style: { width: '20px', height: '20px', marginLeft: '-4px' }, onclick: (e) => { e.stopPropagation(); toggleOpen(); } },
            icon(expanded ? 'caret-down' : 'caret-right')),
          h('span', { class: 'name' }, key.split('\\').pop()),
          isWorktree && h('span', { class: 'badge' }, icon('git-branch'), 'Worktree')),
        h('div', { class: 'row-sub' }, kinds)),
      h('div', { class: 'row-meta', title: 'Newest source file write, checked up to 3 folders deep' }, lastUsed ? `Last used ${ago(lastUsed)}` : 'Last used unknown'),
      sizeCell(bytes(total), total / max))),
    expanded && [...list].sort((a, b) => b.bytes - a.bytes).map((a, _, sorted) => rowWrap(a.path, itemRow(a, sorted[0].bytes))),
  ];
}

function itemRow(a, groupMax) {
  const selected = state.selection.artifacts.has(a.path);
  const toggle = (on) => update((s) => (on ? s.selection.artifacts.add(a.path) : s.selection.artifacts.delete(a.path)));
  const rel = a.path.split('\\').slice(-3).join('\\');
  return h('div', { class: `row clickable ${selected ? 'is-selected' : ''} ${state.busy.has(a.path) ? 'is-busy' : ''}`, style: { paddingLeft: '42px' }, onclick: () => toggle(!selected) },
    checkbox({ checked: selected, label: `Select ${a.path}`, key: `art-${a.path}`, onChange: toggle }),
    h('div', { style: { minWidth: 0 } },
      h('div', { class: 'row-title' }, h('span', { class: 'badge kind' }, a.kind), h('span', { class: 'row-sub', style: { marginTop: 0 } }, a.tool)),
      h('div', { class: 'row-sub' }, h('span', { class: 'mono', title: a.path }, rel))),
    h('div', { class: 'row-meta' },
      a.lastWriteUtc ? ago(a.lastWriteUtc) : '',
      h('div', { class: 'row-actions' },
        h('button', { class: 'icon-btn', type: 'button', title: 'Show in Explorer', 'aria-label': `Show ${a.path} in Explorer`, onclick: (e) => { e.stopPropagation(); reveal(a.path); } }, icon('arrow-square-out')))),
    growthSize('artifacts', a.path, sizeCell(bytes(a.bytes), a.bytes / Math.max(1, groupMax)), a.bytes));
}

function summarizeKinds(list) {
  const by = new Map();
  for (const a of list) {
    const k = a.kind === 'bin' || a.kind === 'obj' ? 'bin & obj' : a.kind;
    by.set(k, (by.get(k) ?? 0) + a.bytes);
  }
  return [...by.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([k, b]) => `${k} ${bytes(b)}`).join(', ')
    + (by.size > 3 ? `, +${by.size - 3} more` : '');
}

export function artifactSelectionBar() {
  const sel = [...state.selection.artifacts].map((p) => state.artifacts.items.get(p)).filter(Boolean);
  if (!sel.length) return null;
  const total = sel.reduce((a, x) => a + x.bytes, 0);
  return [
    h('span', { class: 'sel-count' }, h('strong', null, plural(sel.length, 'folder')), ` selected, ${bytes(total)}`),
    button('Deselect', { variant: 'quiet', small: true, onClick: () => update((s) => s.selection.artifacts.clear()) }),
    button(`Delete ${bytes(total)}`, { variant: 'danger', icon: 'trash', onClick: () => removeArtifacts(sel.map((x) => x.path)), key: 'sel-remove' }),
  ];
}
